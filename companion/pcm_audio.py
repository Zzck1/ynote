"""Ynote decoder adapter for faster-whisper 1.1.1.

Accept only PCM16 mono 16k WAV generated by the managed FFmpeg process. Avoids
redistributing PyAV wheels containing GPL FFmpeg. The ASR engine/weights are unchanged.
"""
import sys,wave
import numpy as np

def decode_audio(input_file,sampling_rate=16000,split_stereo=False):
    if sampling_rate!=16000 or split_stereo:raise ValueError('Ynote 仅接受单声道 16k PCM 输入')
    with wave.open(input_file,'rb') as source:
        if source.getnchannels()!=1 or source.getsampwidth()!=2 or source.getframerate()!=16000 or source.getcomptype()!='NONE':
            raise ValueError('音频必须先由受管理 FFmpeg 转为 16k 单声道 PCM16 WAV')
        data=source.readframes(source.getnframes())
    return np.frombuffer(data,dtype='<i2').astype(np.float32)/32768.0

def pad_or_trim(array,length=3000,*,axis=-1):
    size=array.shape[axis]
    if size>length:
        slices=[slice(None)]*array.ndim;slices[axis]=slice(0,length);return array[tuple(slices)]
    if size<length:
        padding=[(0,0)]*array.ndim;padding[axis]=(0,length-size);return np.pad(array,padding)
    return array

def install():
    sys.modules['faster_whisper.audio']=sys.modules[__name__]
